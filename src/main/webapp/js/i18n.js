const I18n = {
    currentLang: localStorage.getItem('marutham_lang') || 'en',

    init() {
        this.applyLanguage(this.currentLang);
        this.setupSwitcher();
    },

    t(key) {
        return (translations[this.currentLang] && translations[this.currentLang][key]) || key;
    },

    applyLanguage(lang) {
        this.currentLang = lang;
        localStorage.setItem('marutham_lang', lang);
        document.documentElement.lang = lang;

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                const translation = translations[lang][key];

                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    el.placeholder = translation.replace(/<br>/g, ' ');
                } else if (el.tagName === 'OPTION') {
                    el.text = translation;
                } else {
                    el.innerHTML = translation;
                }
            }
        });

        document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    },

    setupSwitcher() {
        const switcher = document.getElementById('lang-switcher');
        if (switcher) {
            switcher.value = this.currentLang;
            switcher.addEventListener('change', (e) => {
                this.applyLanguage(e.target.value);
            });
        }
    }
};

document.addEventListener('DOMContentLoaded', () => I18n.init());